const {
  withAppBuildGradle,
  withMainApplication,
} = require('@expo/config-plugins');

const GRADLE_KEY_BLOCK_START = '// @generated by with-yandex-mapkit-init: key start';
const GRADLE_KEY_BLOCK_END = '// @generated by with-yandex-mapkit-init: key end';
const GRADLE_KEY_BLOCK = `${GRADLE_KEY_BLOCK_START}
def readYandexMapKitApiKeyFromDotEnv = {
    def candidates = [
        new File(projectRoot, ".env.local"),
        new File(projectRoot, ".env")
    ]

    for (def envFile : candidates) {
        if (!envFile.isFile()) {
            continue
        }

        def keyPrefix = "EXPO_PUBLIC_YANDEX_MAPKIT_API_KEY="
        def keyLine = envFile.readLines("UTF-8").find { rawLine ->
            rawLine.trim().startsWith(keyPrefix)
        }
        if (keyLine == null) {
            continue
        }

        def value = keyLine.trim().substring(keyPrefix.length()).trim()
        if (value.length() >= 2) {
            def quotedWithDouble = value.startsWith('"') && value.endsWith('"')
            def quotedWithSingle = value.startsWith("'") && value.endsWith("'")
            if (quotedWithDouble || quotedWithSingle) {
                value = value.substring(1, value.length() - 1)
            }
        }
        if (!value.isEmpty()) {
            return value
        }
    }

    return null
}

def yandexMapKitApiKey = (
    System.getenv("EXPO_PUBLIC_YANDEX_MAPKIT_API_KEY")
        ?: findProperty("YANDEX_MAPKIT_API_KEY")
        ?: readYandexMapKitApiKeyFromDotEnv()
        ?: ""
).replace("\\\\", "\\\\\\\\").replace('"', '\\\\"')

def yandexMapKitReleaseTaskRequested = gradle.startParameter.taskNames.any {
    it.toLowerCase(java.util.Locale.ROOT).contains("release")
}
if (yandexMapKitReleaseTaskRequested && yandexMapKitApiKey.isBlank()) {
    throw new GradleException(
        "Yandex MapKit API key is missing. Set EXPO_PUBLIC_YANDEX_MAPKIT_API_KEY " +
        "in mobile/.env, YANDEX_MAPKIT_API_KEY in Gradle properties, or the environment."
    )
}
${GRADLE_KEY_BLOCK_END}
`;

const BUILD_CONFIG_LINE =
  '        buildConfigField "String", "YANDEX_MAPKIT_API_KEY", "\\"${yandexMapKitApiKey}\\""';
const MAPKIT_DEPENDENCY =
  '    implementation("com.yandex.android:maps.mobile:4.33.1-full")';

const MAPKIT_IMPORT = 'import com.yandex.mapkit.MapKitFactory';
const MAPKIT_INIT_BLOCK = `    if (BuildConfig.YANDEX_MAPKIT_API_KEY.isNotBlank()) {
      MapKitFactory.setLocale("ru_RU")
      MapKitFactory.setApiKey(BuildConfig.YANDEX_MAPKIT_API_KEY)
      MapKitFactory.initialize(this)
    }`;

function withMapKitBuildConfig(config) {
  return withAppBuildGradle(config, (modConfig) => {
    let source = modConfig.modResults.contents;

    const generatedBlockStart = source.indexOf(GRADLE_KEY_BLOCK_START);
    const generatedBlockEnd = source.indexOf(GRADLE_KEY_BLOCK_END);
    if (generatedBlockStart >= 0 && generatedBlockEnd >= generatedBlockStart) {
      const afterGeneratedBlock = generatedBlockEnd + GRADLE_KEY_BLOCK_END.length;
      source =
        source.slice(0, generatedBlockStart) +
        GRADLE_KEY_BLOCK.trimEnd() +
        source.slice(afterGeneratedBlock);
    } else if (source.includes('def yandexMapKitApiKey =')) {
      const legacyBlockStart = source.indexOf('def yandexMapKitApiKey =');
      const legacyBlockEnd = source.indexOf('\n\n/**', legacyBlockStart);
      if (legacyBlockEnd < 0) {
        throw new Error('Unable to update the generated Yandex MapKit key block');
      }
      source =
        source.slice(0, legacyBlockStart) +
        GRADLE_KEY_BLOCK.trimEnd() +
        source.slice(legacyBlockEnd);
    } else {
      source = source.replace(
        'def projectRoot = rootDir.getAbsoluteFile().getParentFile().getAbsolutePath()\n',
        `def projectRoot = rootDir.getAbsoluteFile().getParentFile().getAbsolutePath()\n\n${GRADLE_KEY_BLOCK}`,
      );
    }

    if (!source.includes('buildConfigField "String", "YANDEX_MAPKIT_API_KEY"')) {
      source = source.replace(
        /(\s+buildConfigField "String", "REACT_NATIVE_RELEASE_LEVEL"[^\n]*\n)/,
        `$1${BUILD_CONFIG_LINE}\n`,
      );
    }

    if (!source.includes('implementation("com.yandex.android:maps.mobile:4.33.1-full")')) {
      source = source.replace(
        '    implementation("com.facebook.react:react-android")',
        `    implementation("com.facebook.react:react-android")\n${MAPKIT_DEPENDENCY}`,
      );
    }

    modConfig.modResults.contents = source;
    return modConfig;
  });
}

function withMapKitApplicationInit(config) {
  return withMainApplication(config, (modConfig) => {
    let source = modConfig.modResults.contents;

    if (!source.includes(MAPKIT_IMPORT)) {
      source = source.replace(
        'import android.content.res.Configuration',
        `import android.content.res.Configuration\n\n${MAPKIT_IMPORT}`,
      );
    }

    if (!source.includes('MapKitFactory.setApiKey')) {
      source = source.replace(
        '  override fun onCreate() {\n    super.onCreate()',
        `  override fun onCreate() {\n    super.onCreate()\n${MAPKIT_INIT_BLOCK}`,
      );
    }

    modConfig.modResults.contents = source;
    return modConfig;
  });
}

module.exports = function withYandexMapKitInit(config) {
  config = withMapKitBuildConfig(config);
  return withMapKitApplicationInit(config);
};
