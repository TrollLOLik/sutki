-- Колонка house.country всегда хранила город, а не страну: дефолт был
-- 'Магнитогорск', фильтр каталога сравнивает её с выбранным городом, а список
-- городов строится как SELECT btrim(h.country) AS city. Код это уже обходил
-- алиасами (country AS house_city) и полем City в доменной модели, но само имя
-- в схеме осталось неверным — и на нём легко ошибиться: запрос с h.city
-- проходит проверку sqlc (он валидирует по миграциям) и падает только на живой
-- базе.
--
-- ВНИМАНИЕ ПРИ ДЕПЛОЕ: RENAME COLUMN выполняется мгновенно, но работающий
-- старый код сразу после него начнёт падать на h.country. Порядок: остановить
-- API -> применить миграцию -> запустить новый образ.
ALTER TABLE house RENAME COLUMN country TO city;
